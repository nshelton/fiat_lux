static const uint64_t FONT57[11] = {
    0b01110100111001110111110111011101110ULL,  // '0'
    0b00110011100011000110001100011001111ULL,  // '1'
    0b01110110111001100011001101110011111ULL,  // '2'
    0b11111000100011001111000110011111110ULL,  // '3'
    0b00010001100111010110111110011000110ULL,  // '4'
    0b11111110001111000111000111011101110ULL,  // '5'
    0b00110011001100011110100111001101110ULL,  // '6'
    0b11111100010001100110011100110001100ULL,  // '7'
    0b01110100111001101110100111001101110ULL,  // '8'
    0b01110100111001101111000111011101110ULL,  // '9'
    0b00000001000000000000001000000000000ULL,  // ':'
};

uint16_t glyph3x3(uint8_t c) {
  if (c == 176) return 0b011011000;  // degree sign
  if (c >= 'a' && c <= 'z') c -= 32;
  if (c < 32 || c > 95) return 0;
  return FONT3[c - 32];
}

uint64_t glyph5x7(uint8_t c) {
  if (c < '0' || c > ':') return 0;
  return FONT57[c - '0'];
}
